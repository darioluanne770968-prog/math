// Generate Excel Report
export async function generateExcelReport(data: ReportData): Promise<Blob> {
  // CSV format for Excel compatibility
  let csv = "Learning Progress Report\n\n"

  // Summary section
  csv += "Summary\n"
  csv += "Metric,Value\n"
  csv += `Student Name,${data.studentName}\n`
  csv += `Period Start,${data.period.start.toLocaleDateString()}\n`
  csv += `Period End,${data.period.end.toLocaleDateString()}\n`
  csv += `Total Problems,${data.summary.totalProblems}\n`
  csv += `Correct Answers,${data.summary.correctAnswers}\n`
  csv += `Accuracy,${data.summary.accuracy}%\n`
  csv += `Total Time (min),${data.summary.totalTime}\n`
  csv += `Average Time/Problem (s),${data.summary.averageTimePerProblem}\n`
  csv += `Current Streak,${data.summary.streak}\n`
  csv += `Level,${data.summary.level}\n`
  csv += "\n"

  // Topic breakdown
  csv += "Topic Performance\n"
  csv += "Topic,Problems,Correct,Accuracy,Time Spent (min)\n"
  data.topicBreakdown.forEach((t) => {
    csv += `${t.topic},${t.problems},${t.correct},${t.accuracy}%,${t.timeSpent}\n`
  })
  csv += "\n"

  // Daily activity
  csv += "Daily Activity\n"
  csv += "Date,Problems,Time (min),Accuracy\n"
  data.dailyActivity.forEach((d) => {
    csv += `${d.date},${d.problems},${d.time},${d.accuracy}%\n`
  })
  csv += "\n"

  // Strengths and weaknesses
  csv += "Strengths\n"
  data.strengths.forEach((s) => {
    csv += `${s}\n`
  })
  csv += "\n"

  csv += "Areas for Improvement\n"
  data.weaknesses.forEach((w) => {
    csv += `${w}\n`
  })
  csv += "\n"

  // Recommendations
  csv += "Recommendations\n"
  data.recommendations.forEach((r) => {
    csv += `${r}\n`
  })
  csv += "\n"

  // Achievements
  csv += "Achievements\n"
  csv += "Achievement,Date\n"
  data.achievements.forEach((a) => {
    csv += `${a.name},${a.date.toLocaleDateString()}\n`
  })

  return new Blob([csv], { type: "text/csv" })
}

// Generate JSON Report
export function generateJSONReport(data: ReportData): Blob {
  return new Blob([JSON.stringify(data, null, 2)], { type: "application/json" })
}

// Download helper
export function downloadReport(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob)
  const link = document.createElement("a")
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

