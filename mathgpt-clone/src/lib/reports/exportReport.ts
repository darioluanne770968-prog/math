"use client"

export interface ReportData {
  studentName: string
  period: { start: Date; end: Date }
  summary: {
    totalProblems: number
    correctAnswers: number
    accuracy: number
    totalTime: number
    averageTimePerProblem: number
    streak: number
    level: number
  }
  topicBreakdown: {
    topic: string
    problems: number
    correct: number
    accuracy: number
    timeSpent: number
  }[]
  dailyActivity: {
    date: string
    problems: number
    time: number
    accuracy: number
  }[]
  strengths: string[]
  weaknesses: string[]
  recommendations: string[]
  achievements: { name: string; date: Date }[]
}

